#!/usr/bin/env node
/**
 * Post-build step: put the page Content-Security-Policy in the HTTP headers too.
 *
 * Astro writes the policy (with the SHA-256 of every inline script) as a <meta> tag in each page. A <meta>
 * cannot carry frame-ancestors and public validators (securityheaders.com, MDN Observatory) read only the
 * header, so this step reads the policy from every built page, merges them (pages may differ only in script
 * hashes: anything else fails the build) and appends the rules to dist/_headers for /es, /en, /fr and
 * everything under them. It never writes a rule for /* : Cloudflare merges every matching rule and the strict
 * page policy would break /admin, which has its own.
 *
 * Run after `astro build` (part of `npm run build`).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { mergeCsps, cspProblems, languageRules } from "../src/lib/csp.ts";

const ROOT = path.resolve(fileURLToPath(import.meta.url), "../..");
const DIST = path.join(ROOT, "dist");
const HEADERS = path.join(DIST, "_headers");
const START = "# ---- generated by scripts/build-headers.mjs: page Content-Security-Policy (do not edit) ----";
const END = "# ---- end of generated block ----";

const META_CSP = /<meta\s+http-equiv="content-security-policy"\s+content="([^"]*)"/i;
const decode = (s) => s.replace(/&#39;|&#x27;/g, "'").replace(/&quot;/g, '"').replace(/&amp;/g, "&");

function* htmlFiles(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) {
      if (e.name === "pagefind" || e.name === "_astro" || e.name === "sites" || e.name === "admin") continue;
      yield* htmlFiles(p);
    } else if (e.name.endsWith(".html")) yield p;
  }
}

const policies = new Set();
let pages = 0;
for (const file of htmlFiles(DIST)) {
  const m = META_CSP.exec(fs.readFileSync(file, "utf8"));
  if (m) {
    policies.add(decode(m[1]));
    pages++;
  }
}
if (!pages) {
  console.error("build-headers: no page carries a Content-Security-Policy <meta>; was `astro build` run with security.csp?");
  process.exit(1);
}

const { csp, problems } = mergeCsps([...policies]);
problems.push(...cspProblems(csp));
if (problems.length) {
  console.error("build-headers: the page policies cannot be turned into one header:");
  for (const p of problems) console.error(`  · ${p}`);
  process.exit(1);
}

let current = fs.readFileSync(HEADERS, "utf8");
const i = current.indexOf(START);
if (i >= 0) current = current.slice(0, i); // idempotent: replace a previous block
fs.writeFileSync(HEADERS, `${current.replace(/\s*$/, "\n")}\n${START}\n${languageRules(csp)}${END}\n`);
console.log(`build-headers: CSP header for /es /en /fr from ${pages} pages (${policies.size} distinct ${policies.size === 1 ? "policy" : "policies"}, merged)`);
